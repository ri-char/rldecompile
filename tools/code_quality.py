def compute_elo(save_dir="./"):
    def get_bootstrap_result(battles, func_compute_elo, num_round):
        rows = []
        p = get_progress_bar(console)
        p.start()
        task = p.add_task("bootstrap", total=num_round)
        for _ in range(num_round):
            try:
                rows.append(func_compute_elo(battles.sample(frac=1.0, replace=True)))
            except Exception as e:
                logger.warning(e)
            p.advance(task)
        p.stop()
        df = pd.DataFrame(rows)
        return df[df.median().sort_values(ascending=False).index]

    def compute_mle_elo(df, SCALE=800, BASE=10, INIT_RATING=1000):
        from sklearn.linear_model import LogisticRegression

        ptbl_a_win = pd.pivot_table(
            df[df["winner"] == "model_a"],
            index="model_a",
            columns="model_b",
            aggfunc="size",  # type: ignore
            fill_value=0,
        )
        if sum(df["winner"].isin(["tie", "tie (bothbad)"])) == 0:
            ptbl_tie = pd.DataFrame(
                0, index=ptbl_a_win.index, columns=ptbl_a_win.columns
            )
        else:
            ptbl_tie = pd.pivot_table(
                df[df["winner"].isin(["tie", "tie (bothbad)"])],
                index="model_a",
                columns="model_b",
                aggfunc="size",  # type: ignore
                fill_value=0,
            )
            ptbl_tie = ptbl_tie + ptbl_tie.T

        ptbl_b_win = pd.pivot_table(
            df[df["winner"] == "model_b"],
            index="model_a",
            columns="model_b",
            aggfunc="size",  # type: ignore
            fill_value=0,
        )
        ptbl_win = ptbl_a_win * 2 + ptbl_b_win.T * 2 + ptbl_tie

        models = pd.Series(np.arange(len(ptbl_win.index)), index=ptbl_win.index)

        p = len(models)
        X = np.zeros([p * (p - 1) * 2, p])
        Y = np.zeros(p * (p - 1) * 2)

        cur_row = 0
        sample_weights = []
        for m_a in ptbl_win.index:
            for m_b in ptbl_win.columns:
                if m_a == m_b:
                    continue
                # if nan skip
                if math.isnan(ptbl_win.loc[m_a, m_b]) or math.isnan(
                    ptbl_win.loc[m_b, m_a]
                ):
                    continue
                X[cur_row, models[m_a]] = +math.log(BASE)
                X[cur_row, models[m_b]] = -math.log(BASE)
                Y[cur_row] = 1.0
                sample_weights.append(ptbl_win.loc[m_a, m_b])

                X[cur_row + 1, models[m_a]] = math.log(BASE)
                X[cur_row + 1, models[m_b]] = -math.log(BASE)
                Y[cur_row + 1] = 0.0
                sample_weights.append(ptbl_win.loc[m_b, m_a])
                cur_row += 2
        X = X[:cur_row]
        Y = Y[:cur_row]

        lr = LogisticRegression(fit_intercept=False, penalty=None, tol=1e-6)
        lr.fit(X, Y, sample_weight=sample_weights)
        elo_scores = SCALE * lr.coef_[0] + INIT_RATING
        if calibrate_model in models.index:
            elo_scores += args.calibrate_elo - elo_scores[models[calibrate_model]]
        return pd.Series(elo_scores, index=models.index).sort_values(ascending=False)

    BOOTSTRAP_ROUNDS = 100  # 1000
    calibrate_model = "ghidra"
    chunk_dir = f"{save_dir}/all_chunks"
    pkl_list = os.listdir(chunk_dir)
    df_list = []
    os.makedirs(f"{save_dir}/all_scores", exist_ok=True)
    logger.info(f"pkl_list: {len(pkl_list)}")
    for pkl in pkl_list:
        if not pkl.endswith("pkl"):
            continue
        logger.info(f"pkl: {pkl}")
        with open(f"{chunk_dir}/{pkl}", "rb") as f:
            ret = pickle.load(f)

        for battle in ret:
            metadata = battle["metadata"]
            eval_ret = battle["ret"]

            if not eval_ret:
                continue

            parsed_output = eval_ret["parsed_output"]
            if not parsed_output:
                continue

            model_a = metadata["a"]
            model_b = metadata["b"]
            if type(parsed_output) is not dict:
                logger.info(f"parsed_output: {parsed_output}")
                continue

            for k, v in parsed_output.items():
                try:
                    for kk, vv in v.items():
                        if "winner" not in vv:
                            logger.info(vv.keys())
                            continue

                        winner_value = vv["winner"]
                        if not winner_value:
                            winner = "tie"
                        elif winner_value.lower() == "a":
                            winner = "model_a"
                        elif winner_value.lower() == "b":
                            winner = "model_b"
                        else:
                            winner = "tie"
                        df_list.append(
                            {
                                "model_a": model_a,
                                "model_b": model_b,
                                "ds_idx": metadata["idx"],
                                "aspect": kk,
                                "winner": winner,
                            }
                        )
                except Exception as e:
                    logger.warning(f"parse output error: {e}")
                    continue

    logger.info(f"df_list: {len(df_list)}")
    df = pd.DataFrame(df_list)

    bootstrap_elo_lu = get_bootstrap_result(df, compute_mle_elo, BOOTSTRAP_ROUNDS)
    bootstrap_elo_lu.to_csv(f"{save_dir}/all_scores/elo_scores.csv")
    global aspects
    for aspect in aspects:
        df_aspect = df[df["aspect"] == aspect]
        bootstrap_elo_lu_aspect = get_bootstrap_result(
            df_aspect, compute_mle_elo, BOOTSTRAP_ROUNDS
        )
        bootstrap_elo_lu_aspect.to_csv(f"{save_dir}/all_scores/elo_scores_{aspect}.csv")


def compute_aspect_scores(save_dir="arena_general"):
    global aspects

    model_scores = {}

    for aspect in aspects:
        try:
            df = pd.read_csv(f"{save_dir}/all_scores/elo_scores_{aspect}.csv")
            df = df.drop(columns=["Unnamed: 0"])
            median_scores = df.median()
            for model in median_scores.index:
                if model not in model_scores:
                    model_scores[model] = {}
                model_scores[model][aspect] = median_scores[model]

        except FileNotFoundError:
            logger.warning(f"No scores found for aspect: {aspect}")
            continue

    scores_df = pd.DataFrame(model_scores).T

    scores_df.to_csv(f"{save_dir}/all_scores/model_aspect_scores.csv")

    scores_dict = scores_df.to_dict("index")
    with open(f"{save_dir}/all_scores/model_aspect_scores.json", "w") as f:
        json.dump(scores_dict, f, indent=2)

    return scores_df


def save_scores(save_dir="./code_quality"):
    for aspect in aspects:
        compute_elo(save_dir)
    if not os.path.exists(save_dir):
        os.makedirs(save_dir)
    compute_aspect_scores(save_dir)


async def export_csv():
    from lib.utils import client

    tables = {"problem_id": [], "func": []}
    for m in decompilers:
        tables[m] = []
    count = await client["exebench"].count_documents(
        {"label": "real_test"},
    )
    p = get_progress_bar()
    p.start()
    task = p.add_task("save", total=count * 5)

    queue: asyncio.Queue[tuple[dict[str, str], str]] = asyncio.Queue(68)

    async def worker():
        while True:
            row, opt_level = await queue.get()
            problem_id = row["id"]
            func_def = row["func_def"]
            row = {"problem_id": problem_id, "func": func_def}
            ghidra_decompiled_code = []
            async for function in client["functions"].find(
                {"binary": problem_id, "optLevel": opt_level}
            ):
                ghidra_decompiled_code.append(function["decompiled_code"])
            row["ghidra"] = "\n".join(ghidra_decompiled_code)
            for model_name in decompilers:
                if model_name == "ghidra":
                    continue
                ans = await client["llm_ans_log"].find_one(
                    {
                        "problem_id": problem_id,
                        "model_name": model_name,
                        "optLevel": opt_level,
                    },
                    projection={"ans": 1, "_id": 0},
                )
                if ans is None:
                    break
                else:
                    row[model_name] = ans["ans"]
            else:
                for k, v in row.items():
                    tables[k].append(v)
            p.advance(task)
            queue.task_done()

    workers = [asyncio.create_task(worker()) for _ in range(64)]

    async for row in client["exebench"].find(
        {"label": "real_test"},
        projection={"_id": False, "id": True, "func_def": True},
    ):
        for opt_level in ["O0", "O1", "O2", "O3", "Os"]:
            await queue.put((row, opt_level))

    await queue.join()

    p.stop()
    for w in workers:
        w.cancel()

    datasets.Dataset.from_dict(tables).save_to_disk(args.dataset)


if __name__ == "__main__":
    console = init_log("DEBUG")
    if args.export_csv:
        asyncio.run(export_csv())
    if args.run:
        asyncio.run(main())
    if args.rate:
        save_scores(args.output)
