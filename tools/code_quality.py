async def invoke(src, dec_a, dec_b, metadata):
    parse_retry = 0
    while True:
        try:
            ret = await chain.ainvoke(
                {
                    "source_code": src,
                    "decompile_code_a": dec_a,
                    "decompile_code_b": dec_b,
                }
            )

            break
        except langchain_core.exceptions.OutputParserException:
            if parse_retry >= 3:
                return None
            logger.warning("parse result error, retry")
            parse_retry += 1
        except Exception as e:
            if "rate limit" in str(e):
                logger.warning("reach rate limit, retry later")
                await asyncio.sleep(15)
            else:
                raise
    return {
        "ret": ret,
        "metadata": metadata,
    }


def choose_by_elo(rating: Dict[str, int], model_a):
    selection_probs = []
    rating_diff_list = []
    model_list = [model for model in rating.keys() if model != model_a]
    for model_b in model_list:
        rating_diff = abs(rating[model_a] - rating[model_b])
        rating_diff_list.append(rating_diff)
    rating_diff_min = min(rating_diff_list) + 1e-6
    for rating_diff in rating_diff_list:
        selection_prob = 1 / (1 + rating_diff / rating_diff_min)
        selection_probs.append(selection_prob)

    total_prob = sum(selection_probs)
    normalized_probs = [prob / total_prob for prob in selection_probs]

    selected_b = np.random.choice(len(model_list), p=normalized_probs)

    return model_list[selected_b]


async def run(df: pd.DataFrame, rating: Dict[str, int], p: Progress):
    result = []
    decompilers = list(rating.keys())

    process_bar_task = p.add_task("chunk", total=len(df))

    handle_queue: asyncio.Queue = asyncio.Queue(4)

    async def worker():
        while True:
            task_handle = await handle_queue.get()
            result.append(await asyncio.wait_for(task_handle, None))
            handle_queue.task_done()
            p.advance(process_bar_task)

    worker_thread = asyncio.create_task(worker())

    for idx, row in df.iterrows():
        dec_a: str = np.random.choice(decompilers)
        source_code = row["func"]
        dec_b: str = choose_by_elo(rating, dec_a)
        if np.random.random() < 0.5:
            dec_a, dec_b = dec_b, dec_a

        dec_a_res = row[dec_a]
        dec_b_res = row[dec_b]

        if not dec_a_res or not dec_b_res or dec_a_res == "none" or dec_b_res == "none":
            p.advance(process_bar_task)
            continue

        await handle_queue.put(
            asyncio.create_task(
                invoke(
                    src=source_code,
                    dec_a=dec_a_res,
                    dec_b=dec_b_res,
                    metadata={
                        "idx": idx,
                        "a": dec_a,
                        "b": dec_b,
                    },
                )
            )
        )
    await handle_queue.join()
    worker_thread.cancel()
    p.remove_task(process_bar_task)
    return result


